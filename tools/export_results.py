"""Export the October 2026 results (Excel workbook + close summary memo) to results/.

Run:  python tools/export_results.py
The same workbook is available from the app's sidebar ("Download results").
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from engine.packet import SAMPLE_DIR, load_baseline, prepare_month, sample_cutoff  # noqa: E402
from engine.report import to_excel, totals  # noqa: E402
from engine.review import ERROR, FOLLOW_UP, NEEDS_INFO, VALID, run_review  # noqa: E402
from engine.util import fmt_usd  # noqa: E402


def main():
    out = os.path.join(ROOT, "results")
    os.makedirs(out, exist_ok=True)
    m = prepare_month(SAMPLE_DIR, load_baseline())
    terms, approvals = m["terms"], m["approvals"]
    r = run_review(m["tables"], terms, approvals, 2026, 10, sample_cutoff(), m["expected_counts"])
    with open(os.path.join(out, "billing_review_2026_10.xlsx"), "wb") as fh:
        fh.write(to_excel(r, terms, approvals))
    t = totals(r)
    L = []
    L.append("# RelayCloud – October 2026 Billing Review: Close Summary\n")
    L.append(f"Review period: **{r.period_label} service** · close cutoff **2026-11-11 18:00 MT** · 30 customers · "
             "generated by the Billing Review app from the supplied files. All corrections are **proposals for Controller approval**.\n")
    L.append("## 1. What should we have billed, and how does it compare?\n")
    L.append("| | Expected | Actual | Difference |\n|---|---:|---:|---:|")
    L.append(f"| Platform invoices covering October | {fmt_usd(t['expected_platform'])} | {fmt_usd(t['actual_platform'])} | {fmt_usd(t['actual_platform'] - t['expected_platform'], True)} |")
    L.append(f"| Usage for October service (net of approved concession) | {fmt_usd(t['expected_usage'])} | {fmt_usd(t['billed_usage'])} | {fmt_usd(t['billed_usage'] - t['expected_usage'], True)} |")
    L.append(f"| Platform revenue earned in October (days/365) | {fmt_usd(t['expected_rev'])} | GL {fmt_usd(t['gl_rev'])} | {fmt_usd(t['gl_rev'] - t['expected_rev'], True)} |")
    L.append(f"| Usage revenue accrued for October | {fmt_usd(t['expected_usage'])} | GL {fmt_usd(t['accrued_usage'])} | {fmt_usd(t['accrued_usage'] - t['expected_usage'], True)} |\n")
    L.append(f"**Under-billed {fmt_usd(t['under_billed'])} · Over-billed {fmt_usd(t['over_billed'])}** (confirmed errors only; shown separately, never netted).  ")
    L.append(f"**October revenue understated {fmt_usd(t['rev_understated'])} · overstated {fmt_usd(t['rev_overstated'])} · net {fmt_usd(t['rev_net'], True)}.**\n")
    L.append("Platform basis: invoice billing periods covering October (annual prepaid invoices cover October with no new invoice); "
             "revenue measured separately at annual consideration × service days / 365.\n")
    L.append("## 2. Which differences need action?\n")
    L.append("| ID | Priority | Customer | Finding | Billing effect | Oct revenue effect | Billing action (Nov) | October accounting | Owner |\n|---|---|---|---|---:|---:|---|---|---|")
    for f in r.findings:
        if f.classification == ERROR:
            L.append(f"| {f.id} | {f.priority} | {f.customer} | {f.title} | {fmt_usd(f.billing_effect, True)} | {fmt_usd(f.revenue_effect, True)} | "
                     f"{f.billing_action or '—'} | {f.accounting_action} | {f.owner} |")
    L.append("")
    for f in r.findings:
        if f.classification == ERROR:
            L.append(f"**{f.id} {f.customer} – {f.title}.** {f.root_cause}  \n*Billing vs revenue:* {f.why_billing_only}\n")
    L.append("### Needs more information (not in totals)\n")
    for f in r.findings:
        if f.classification == NEEDS_INFO:
            L.append(f"- **{f.customer} – {f.title}.** {f.conditional_exposure + '. ' if f.conditional_exposure else ''}{f.next_step}")
    L.append("\n### Later-service follow-ups\n")
    for f in r.findings:
        if f.classification == FOLLOW_UP:
            L.append(f"- **{f.customer} – {f.title}.** {f.conditional_exposure}. {f.next_step}")
    L.append("\n### Valid explanations (no action)\n")
    for f in r.findings:
        if f.classification == VALID:
            L.append(f"- **{f.customer} – {f.title}.** {f.root_cause}")
    L.append("\n## Proposed October journal entries (posting period Oct 2026)\n")
    for j in r.journals:
        L.append(f"**{j['je_id']} – {j['title']}** (date {j['date']}, finding {j['finding']})\n")
        L.append("| Account | Debit | Credit | Memo |\n|---|---:|---:|---|")
        for l in j["lines"]:
            L.append(f"| {l['account']} {l['account_name']} | {fmt_usd(l['debit']) if l['debit'] else ''} | {fmt_usd(l['credit']) if l['credit'] else ''} | {l['memo']} |")
        L.append("")
    L.append("## Proposed billing documents (November issue dates)\n")
    L.append("| Finding | Customer | Document | Linked to | Service period | Amount | GL when issued |\n|---|---|---|---|---|---:|---|")
    for b in r.billing_docs:
        L.append(f"| {b['finding']} | {b['customer']} | {b['type']} | {b['linked_to']} | {b['service_period']} | {fmt_usd(b['amount'])} | {b['gl_when_issued']} |")
    L.append("\n## Recommended revenue plan updates\n")
    for p in r.plan_updates:
        L.append(f"- **{p['customer']}:** {p['recommendation']}")
    L.append("\n## 3. Catching this next month\n")
    L.append("The app runs 12 controls for every customer on every run (Controls page / Excel 'Controls matrix'). "
             "This month's failures map to: amendment not loaded to billing (Cedar, Meridian), billed rate ≠ contract rate (Juniper), "
             "usage invoice/accrual completeness (Yarrow), late-ingested usage (Beacon), accrual copied from the invoice instead of recalculated "
             "(Juniper, Cedar), revenue plan missing an amendment (Meridian), and unverified usage (workspace pa_676b6b455e0887 / Willow Passage). "
             "Recommended routine: run the review on draft usage invoices on the 1st, before finalizing, and build the month-end usage accrual from "
             "the review rather than from billed amounts.\n")
    L.append("## Data health\n")
    for c in r.checks:
        L.append(f"- **{c['result']}** – {c['check']}: {c['detail']}")
    with open(os.path.join(out, "OCTOBER_2026_CLOSE_SUMMARY.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("Wrote results/billing_review_2026_10.xlsx and results/OCTOBER_2026_CLOSE_SUMMARY.md")


if __name__ == "__main__":
    main()
